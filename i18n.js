function t(key, vars) {
  const dict = TRANSLATIONS[settings.language] || TRANSLATIONS.fr;
  let str = dict[key] ?? TRANSLATIONS.fr[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replaceAll(`{${k}}`, v);
    });
  }
  return str;
}

// Applique les traductions à tout le DOM statique marqué avec data-i18n(-*).
function applyTranslations() {
  document.documentElement.lang = settings.language;
  document.title = t("app.title");

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  // Contenu du tooltip custom (voir app.js) : stocké en data-attribute, pas en
  // `title`, pour ne pas déclencher aussi l'infobulle native du navigateur.
  document.querySelectorAll("[data-i18n-tooltip]").forEach((el) => {
    el.dataset.tooltip = t(el.dataset.i18nTooltip);
  });
}
